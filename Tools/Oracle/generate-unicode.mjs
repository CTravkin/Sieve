import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { nativeUnicodeLower, nativeUnicodeNormalization } from './runner.mjs';

const { unicode, pairs } = await nativeUnicodeLower();
assert.equal(unicode, '17.0.0', 'The committed core tables are pinned to Go Unicode 17.0.0');
// Unicode mappings are data derived from the pinned Go oracle, not JS contextual casing.
const lines = pairs.map(([upper, lower]) => `  [${upper}, ${lower}],`).join('\n');
await mkdir(new URL('../../src/core/', import.meta.url), { recursive: true });
await writeFile(new URL('../../src/core/unicode-lower.ts', import.meta.url),
  `// Generated by Tools/Oracle/generate-unicode.mjs with Go Unicode ${unicode}.\n` +
  `/*! @license Go Authors BSD-3-Clause and Unicode-3.0; see THIRD-PARTY-NOTICES.md */\n` +
  `export const unicodeVersion = ${JSON.stringify(unicode)};\n` +
  `const simpleLower = new Map<number, number>([\n${lines}\n]);\n` +
  `export function lowerRune(rune: number): number { return simpleLower.get(rune) ?? rune; }\n`);
console.log(`Generated ${pairs.length} simple lowercase mappings for Unicode ${unicode}`);

const normalization = await nativeUnicodeNormalization();
assert.equal(normalization.unicode, '17.0.0');
const entries = xs => xs.map(x => `  ${JSON.stringify(x)},`).join('\n');
await writeFile(new URL('../../src/core/unicode-normalization.ts', import.meta.url),
  `// Generated by Tools/Oracle/generate-unicode.mjs from pinned Go Unicode 17.0.0.\n` +
  `/*! @license Go Authors BSD-3-Clause and Unicode-3.0; see THIRD-PARTY-NOTICES.md */\n` +
  `const decompositions = new Map<number, readonly number[]>([\n${entries(normalization.decompositions)}\n]);\n` +
  `const combiningClasses = new Map<number, number>([\n${entries(normalization.combining)}\n]);\n` +
  `const compositions = new Map<number, number>([\n${entries(normalization.compositions.map(([a,b,c]) => [a*0x110000+b,c]))}\n]);\n` +
  `const streamSafe = new Map<number, readonly [number, number]>([\n${entries(normalization.streamSafe.map(([cp,lead,trail]) => [cp,[lead,trail]]))}\n]);\n` +
  `export function decomposeRune(rune: number): readonly number[] | undefined { return decompositions.get(rune); }\n` +
  `export function combiningClass(rune: number): number { return combiningClasses.get(rune) ?? 0; }\n` +
  `export function composeRunes(first: number, second: number): number | undefined { return compositions.get(first*0x110000+second); }\n` +
  `export function nonStarterCounts(rune: number): readonly [number, number] { return rune >= 0xac00 && rune <= 0xd7a3 ? [0,(rune-0xac00)%28===0?1:2] : streamSafe.get(rune) ?? [0,0]; }\n`);
console.log(`Generated ${normalization.decompositions.length} decompositions, ${normalization.combining.length} combining classes, ${normalization.compositions.length} compositions`);
